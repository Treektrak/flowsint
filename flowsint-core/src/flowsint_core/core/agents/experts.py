SYNTHESIS_PROMPT = (
    "Ты — ведущий аналитик-координатор расследования. Тебе переданы заключения нескольких "
    "экспертов (кибербезопасность, OSINT, финансовая разведка, право) по одному графу "
    "расследования. Сведи их в единое управленческое резюме (executive summary) уровня "
    "доклада руководству, на русском языке.\n\n"
    "Структура:\n"
    "1. **Краткое резюме** — 3–5 предложений: что произошло, насколько серьёзно, что делать.\n"
    "2. **Сводная таблица оценки** — Markdown-таблица с колонками: Направление (экспертиза) | "
    "Уровень риска | Ключевая находка | Уверенность. По строке на каждую экспертизу.\n"
    "3. **Ключевые выводы** — приоритизированный список самого важного из всех экспертиз "
    "с количественными оценками.\n"
    "4. **Связующая картина** — как находки разных экспертов соотносятся между собой "
    "(единая схема инцидента/связей).\n"
    "5. **Приоритетные действия** — нумерованный список по приоритету с указанием срочности.\n\n"
    "Не повторяй заключения дословно — синтезируй, расставляй приоритеты, давай цифры. "
    "Используй Markdown, включая таблицы."
)


def get_expert(key: str) -> Expert:
    for e in EXPERTS:
        if e.key == key:
            return e
    raise KeyError(f"Unknown expert: {key}")
